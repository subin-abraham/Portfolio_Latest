/**
 * Fetch Hygraph Asset URLs and emit SQL that:
 *  1) upserts rows into media_assets
 *  2) links tools.media_asset_id by matching slug ↔ fileName (sans extension)
 *
 * Usage:
 *   HYGRAPH_ENDPOINT=... HYGRAPH_MANAGEMENT_TOKEN=... \
 *   HYGRAPH_ASSET_STAGE=DRAFT \
 *   npx tsx scripts/sync-hygraph-tool-media.ts
 *
 * Optional: --apply  writes to Neon via DATABASE_URL after generating SQL.
 * Optional: --out path  (default sql/011_seed_tool_media.sql)
 */
import "dotenv/config";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { neon } from "@neondatabase/serverless";

const TOOL_SLUGS = [
  "javascript",
  "typescript",
  "python",
  "java",
  "angular",
  "nextjs",
  "react",
  "html5",
  "css3",
  "sass",
  "tailwindcss",
  "bootstrap",
  "nodejs",
  "express",
  "graphql",
  "springboot",
  "postgresql",
  "mysql",
  "mongodb",
  "aws-quicksight",
  "github",
  "git",
  "openai",
  "hygraph",
  "jira",
  "cursor",
] as const;

type HygraphAsset = {
  id: string;
  fileName: string;
  url: string;
  mimeType: string | null;
};

type AssetsResponse = {
  data?: { assets?: HygraphAsset[] };
  errors?: Array<{ message?: string }>;
};

function slugFromFileName(fileName: string): string {
  return fileName.replace(/\.[^.]+$/, "").toLowerCase();
}

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function parseArgs(argv: string[]) {
  const apply = argv.includes("--apply");
  const outIdx = argv.indexOf("--out");
  const out =
    outIdx >= 0 && argv[outIdx + 1]
      ? resolve(argv[outIdx + 1])
      : resolve("sql/011_seed_tool_media.sql");
  return { apply, out };
}

async function fetchHygraphAssets(): Promise<HygraphAsset[]> {
  const endpoint = process.env.HYGRAPH_ENDPOINT?.trim();
  const token = process.env.HYGRAPH_MANAGEMENT_TOKEN?.trim();
  const stage = (process.env.HYGRAPH_ASSET_STAGE?.trim() || "DRAFT").toUpperCase();

  if (!endpoint || !token) {
    throw new Error(
      "Set HYGRAPH_ENDPOINT and HYGRAPH_MANAGEMENT_TOKEN in .env (Content API URL + Permanent Auth Token)."
    );
  }

  const query = `
    query ToolAssets($stage: Stage!) {
      assets(first: 100, stage: $stage, orderBy: fileName_ASC) {
        id
        fileName
        url
        mimeType
      }
    }
  `;

  const res = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${token}`,
    },
    body: JSON.stringify({ query, variables: { stage } }),
  });

  if (!res.ok) {
    throw new Error(`Hygraph request failed (${res.status})`);
  }

  const json = (await res.json()) as AssetsResponse;
  if (json.errors?.length) {
    const msg = json.errors[0]?.message || "Hygraph GraphQL error";
    if (/not allowed/i.test(msg) && stage === "DRAFT") {
      throw new Error(
        "Hygraph token cannot read DRAFT assets. In Studio: Assets → select all → Publish, then set HYGRAPH_ASSET_STAGE=PUBLISHED and re-run. Or grant the token Content API Read on Asset (Draft)."
      );
    }
    throw new Error(msg);
  }

  const assets = json.data?.assets ?? [];
  if (!assets.length) {
    throw new Error(
      `No assets returned for stage=${stage}. Publish the uploaded SVGs in Hygraph Studio (Assets → Publish), set HYGRAPH_ASSET_STAGE=PUBLISHED, then re-run.`
    );
  }

  return assets;
}

function buildSql(matched: Array<HygraphAsset & { slug: string }>): string {
  const values = matched
    .map((a) => {
      const alt = a.slug.replace(/-/g, " ");
      const mime = a.mimeType || "image/svg+xml";
      return `  ('HYGRAPH', ${sqlString(a.id)}, ${sqlString(a.url)}, ${sqlString(alt)}, ${sqlString(mime)}, ${sqlString(a.fileName)})`;
    })
    .join(",\n");

  return `-- Generated by scripts/sync-hygraph-tool-media.ts
-- Do not edit by hand; re-run the script after uploading assets in Hygraph.
-- Upserts media_assets, then links tools.media_asset_id where slug matches fileName.

WITH upserted AS (
  INSERT INTO media_assets (provider, asset_id, url, alt_text, mime_type, file_name)
  VALUES
${values}
  ON CONFLICT (provider, asset_id) DO UPDATE SET
    url = EXCLUDED.url,
    alt_text = EXCLUDED.alt_text,
    mime_type = EXCLUDED.mime_type,
    file_name = EXCLUDED.file_name,
    updated_at = NOW()
  RETURNING id, file_name
)
UPDATE tools AS t
SET
  media_asset_id = u.id,
  updated_at = NOW()
FROM upserted AS u
WHERE t.slug = lower(regexp_replace(u.file_name, '\\.[^.]+$', ''));
`;
}

async function main() {
  const { apply, out } = parseArgs(process.argv.slice(2));
  const assets = await fetchHygraphAssets();

  const bySlug = new Map<string, HygraphAsset>();
  for (const asset of assets) {
    if (!asset.url?.trim()) continue;
    const slug = slugFromFileName(asset.fileName);
    // Prefer exact tool slug matches; keep first if duplicates
    if (!bySlug.has(slug)) bySlug.set(slug, asset);
  }

  const matched: Array<HygraphAsset & { slug: string }> = [];
  const missing: string[] = [];

  for (const slug of TOOL_SLUGS) {
    const asset = bySlug.get(slug);
    if (asset) matched.push({ ...asset, slug });
    else missing.push(slug);
  }

  const unmatched = [...bySlug.keys()].filter(
    (slug) => !(TOOL_SLUGS as readonly string[]).includes(slug)
  );

  const sql = buildSql(matched);
  writeFileSync(out, sql, "utf8");

  console.log(`Wrote ${matched.length} tool media bindings → ${out}`);
  if (missing.length) {
    console.warn(`Missing Hygraph assets for tools: ${missing.join(", ")}`);
  }
  if (unmatched.length) {
    console.warn(`Hygraph assets with no tool slug: ${unmatched.join(", ")}`);
  }

  if (!apply) {
    console.log("Run with --apply to execute against DATABASE_URL.");
    return;
  }

  const databaseUrl = process.env.DATABASE_URL?.trim();
  if (!databaseUrl) {
    throw new Error("--apply requires DATABASE_URL");
  }

  const db = neon(databaseUrl);
  for (const a of matched) {
    const mime = a.mimeType || "image/svg+xml";
    const alt = a.slug.replace(/-/g, " ");
    await db`
      INSERT INTO media_assets (provider, asset_id, url, alt_text, mime_type, file_name)
      VALUES ('HYGRAPH', ${a.id}, ${a.url}, ${alt}, ${mime}, ${a.fileName})
      ON CONFLICT (provider, asset_id) DO UPDATE SET
        url = EXCLUDED.url,
        alt_text = EXCLUDED.alt_text,
        mime_type = EXCLUDED.mime_type,
        file_name = EXCLUDED.file_name,
        updated_at = NOW()
    `;
    await db`
      UPDATE tools
      SET
        media_asset_id = (
          SELECT id FROM media_assets
          WHERE provider = 'HYGRAPH' AND asset_id = ${a.id}
        ),
        updated_at = NOW()
      WHERE slug = ${a.slug}
    `;
  }
  console.log(`Applied ${matched.length} media links to Neon.`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
